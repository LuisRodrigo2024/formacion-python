### Operadores ###
print("Operadores Aritméticos")
# Suma
print("Suma: ", 5 + 3)

# Resta
print("Resta: ", 5 - 3)

# Multiplicación
print("Multiplicación: ", 5 * 3)

# División
print("División: ", 5 / 3)

# División entera
print("División entera: ", 5 // 3)

# Módulo
print("Módulo: ", 5 % 3)

# Potencia
print("Potencia: ", 5 ** 3)

# Concatenación de cadenas
print("Hola" + " " + "Mundo")
print ("Hola " * 5)
print ("Hola " * (2**3))

my_float = 1.5 * 2
print ("Hola " * int(my_float))

#### Operadores de Comparación con números ###
print("Operadores de Comparación")
print("5 > 3: ", 5 > 3)
print("5 < 3: ", 5 < 3)
print("5 >= 3: ", 5 >= 3)
print("5 <= 3: ", 5 <= 3)
print("5 == 3: ", 5 == 3)
print("5 != 3: ", 5 != 3)

#### Operadores de Comparación con cadenas ###
print("Operadores de Comparación con cadenas")
print("Hola" > "Python")
print("Hola" < "Python")
print("aaaa" >= "abaa") # Ordenación alfabética por código ASCII
print("Hola" <= "Python")
print("Hola" == "Hola")
print("Hola" != "Python")

### Coomparación de tamaño de cadenas ###
print("Comparación de tamaño de cadenas")
print(len("Hola") == len("Bola"))

### Operadores Lógicos ###
print("Operadores Lógicos")
print("True and True: ", True and True)
print("True and False: ", True and False)
print("False and True: ", False and True)
print("False and False: ", False and False)
print("True or True: ", True or True)
print("True or False: ", True or False)
print("False or True: ", False or True)
print("False or False: ", False or False)
print("not True: ", not True)
print("not False: ", not False)

